#!/usr/bin/env python3
# coding: utf-8
"""Build the visual contract from its single reviewed source."""
import argparse,json,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def artifacts():
    source=json.loads((ROOT/'design/system.json').read_text())
    tokens=source['tokens']
    if len(tokens)!=len(set(tokens))or any(not re.fullmatch(r'[a-z][a-z0-9-]*',name)for name in tokens):raise ValueError('Invalid token names')
    for value in tokens.values():
        if not isinstance(value,str)or any(c in value for c in ['{','}',';','\n']):raise ValueError('Invalid token value')
    css='/* Generated by ops/design_system.py from design/system.json. */\n:root{\n'+''.join('  --'+name+':'+value+';\n'for name,value in tokens.items())+'}\n'
    return {ROOT/'public/css/design-tokens.css':css,ROOT/'public/design-system.json':json.dumps(source,ensure_ascii=False,indent=2)+'\n'}
def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--write',action='store_true');args=parser.parse_args()
    for file,content in artifacts().items():
        if args.write:file.write_text(content)
        elif not file.is_file()or file.read_text()!=content:raise SystemExit('Generated design contract differs: '+str(file.relative_to(ROOT)))
    print(json.dumps({'design_contract':True,'generated_files':2,'written':args.write}))
if __name__=='__main__':main()
