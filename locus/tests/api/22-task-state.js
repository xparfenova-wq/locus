const assert=require('node:assert/strict');
const {nado,zapros,proverit}=require('../prover.js');
module.exports=async()=>{
  const make=async(body)=>(await nado('POST','/api/zadachi',{telo:{nazvanie:'Versioned close',napravlenie:'synapt',otvetstvennyj:2,tip:'vnutrennjaja',...body}})).telo;
  const get=async(number)=>(await nado('GET','/api/zadachi/'+number)).telo;
  const parent=await make({status:'v_processe'}),child=await make({roditel_id:parent.id});
  const seen=await get(parent.nomer);
  const peer=(await nado('PATCH','/api/zadachi/'+parent.nomer,{telo:{versija:seen.versija,status:'na_soglasovanii'}})).telo;
  const stale=await zapros('POST','/api/zadachi/'+parent.nomer+'/zakryt',{telo:{versija:seen.versija,i_podzadachi:true}});
  assert.equal(stale.kod,409);assert.equal((await get(parent.nomer)).status,'na_soglasovanii');assert.equal((await get(child.nomer)).status,child.status);
  proverit('устаревшее закрытие не меняет родителя и подзадачу',true);
  const saved=(await nado('POST','/api/zadachi/'+parent.nomer+'/zakryt',{telo:{versija:peer.versija,i_podzadachi:true,versii_podzadach:peer.podzadachi.map(p=>({id:p.id,versija:p.versija}))}})).telo;
  assert.equal(saved.status,'sdelano');assert.equal(saved.versija,peer.versija+1);assert.equal((await get(child.nomer)).status,'sdelano');
  assert.equal((await zapros('POST','/api/zadachi/'+parent.nomer+'/zakryt',{telo:{versija:peer.versija}})).kod,409);
  const again=(await nado('POST','/api/zadachi/'+parent.nomer+'/zakryt',{telo:{versija:saved.versija}})).telo;
  assert.equal(again.versija,saved.versija);
  proverit('закрытие с увиденной версией и повтор без лишнего изменения',true);
  assert.equal((await zapros('PATCH','/api/zadachi/'+parent.nomer,{telo:{versija:peer.versija,status:'v_processe'}})).kod,409);
  assert.equal((await get(parent.nomer)).status,'sdelano');assert.equal((await get(parent.nomer)).versija,saved.versija);
  proverit('отмена с прежней версией не заменяет последующую запись',true);
  const today=new Intl.DateTimeFormat('sv-SE',{timeZone:'Europe/Moscow'}).format(new Date());
  const past=new Date(Date.parse(today+'T12:00:00Z')-86400000).toISOString().slice(0,10);
  const repeat=await make({povtorjaetsja:true,chastota:'kazhdyj_den',povtor_s:past});
  const marked=(await nado('POST','/api/zadachi/'+repeat.nomer+'/otmetki',{telo:{versija:repeat.versija,data:past}})).telo;
  assert.equal(marked.zadacha.den_vybora,past);assert.equal(marked.zadacha.otmecheno,true);
  assert.equal((await get(repeat.nomer)).otmecheno,false);
  proverit('ответ отметки относится к выбранному дню, сегодняшний остаётся отдельным',true);
  const calendar=require('../../api/kalendar.js'),week=calendar.iso_nedelja(today),next=calendar.sdvinut_nedelju(week.god,week.nomer,1);
  const future=(await nado('GET','/api/zadachi?sprint='+calendar.kljuch_nedeli(next.god,next.nomer)+'&na_stranice=1000')).telo.spisok.find(z=>z.nomer===repeat.nomer);
  assert.ok(future);assert.equal(future.den_vybora,next.nachalo);assert.equal(future.buduschij_den,true);
  proverit('повтор в будущей неделе не подменяется сегодняшним днём',true);
  const current=await get(repeat.nomer);
  const planPath='/api/planerka?napravlenie=synapt&nedelja=';
  const beforeCurrent=(await nado('GET',planPath+calendar.kljuch_nedeli(week.god,week.nomer))).telo.svodka;
  const beforeFuture=(await nado('GET',planPath+calendar.kljuch_nedeli(next.god,next.nomer))).telo.svodka;
  await nado('POST','/api/zadachi/'+repeat.nomer+'/otmetki',{telo:{versija:current.versija,data:today}});
  const afterCurrent=(await nado('GET',planPath+calendar.kljuch_nedeli(week.god,week.nomer))).telo.svodka;
  const afterFuture=(await nado('GET',planPath+calendar.kljuch_nedeli(next.god,next.nomer))).telo.svodka;
  assert.equal(afterCurrent.zakryto,beforeCurrent.zakryto+1);assert.equal(afterCurrent.otkryto,beforeCurrent.otkryto-1);
  assert.equal(afterFuture.zakryto,beforeFuture.zakryto);
  proverit('отметка меняет сводку текущей планёрки и не закрывает повтор будущей',true);
  const q='?sprint='+calendar.kljuch_nedeli(next.god,next.nomer)+'&napravlenie=synapt&otvetstvennyj=2';
  const done=(await nado('GET','/api/zadachi'+q+'&status=sdelano&na_stranice=1000')).telo;
  assert.ok(!done.spisok.some(z=>z.nomer===repeat.nomer));
  const planned=(await nado('GET','/api/zadachi'+q+'&status=v_plane&na_stranice=1000')).telo;
  assert.ok(planned.spisok.some(z=>z.nomer===repeat.nomer));
  const summary=(await nado('GET','/api/zadachi/svodka'+q+'&status=v_plane')).telo;
  assert.equal(summary.po_statusu.v_plane,planned.vsego);
  proverit('фильтр и сводка будущего спринта используют тот же день, что строки',true);
};
